/**
 * لمسة اهتزاز حيث يتيحها الجهاز.
 *
 * الاهتزاز تأكيدٌ إضافي، لا التأكيد الوحيد: كل موضع يستدعيه يعرض
 * كذلك تنبيهًا أو يحرّك شيئًا على الشاشة — فلا يضيع شيء على Safari في
 * iOS (لا يدعم واجهة الاهتزاز أصلًا) ولا على جهاز أُطفئ اهتزازه.
 *
 * المدد قصيرة عمدًا: النقرة يجب أن تُحسّ طقّة لا طنينًا.
 */

const PATTERNS = {
  /** ضُغط عنصر: تبويب، رقاقة، زرّ كمية */
  tap: 8,
  /** كُتب شيء: أُضيف إلى السلة، أُكّد طلب */
  success: [14, 36, 14],
  /** حُذف شيء أو رُفض */
  warn: [22, 44, 22],
};

export function haptic(kind = 'tap') {
  if (typeof navigator === 'undefined' || typeof navigator.vibrate !== 'function') return;
  try {
    navigator.vibrate(PATTERNS[kind] ?? PATTERNS.tap);
  } catch {
    // متصفّح يعرض الواجهة ثم يرفضها (سياسة صلاحيات أو تبويب في الخلفية)
    // لا يجوز أن يُسقط التفاعل معه.
  }
}
